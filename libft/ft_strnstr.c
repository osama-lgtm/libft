char	*ft_strnstr(const char *B,const char *S, size_t n)
{
	int i;
	i = 0;
	while(*B != '\0' && n == 0)
	{
		if (S[i] == *B)
			i++;
		else
			i = 0;
		if (S)
			return S;
		n--;
		B++;
	}
	return (0);
}