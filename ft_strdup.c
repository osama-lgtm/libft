char	*ft_strdup(const char *str1)
{
	int	i = 0;
	while (str1[i] != '\0')
		i++;
	char *str2 = malloc(sizeof(char) * (i + 1));
	i = 0;
	while(str1[i] != '\0')
	{
		str2[i] = str1[i];
		i++;
	}
	str2[i] = '\0';
	return str2;
}